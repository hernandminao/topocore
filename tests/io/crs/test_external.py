def test_whitespace_only_prj_returns_none(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    data_path = _write_pair(tmp_path, "whitespace_prj", "xyz", "   \n\n   ")
    assert detector.detect(data_path) is None


def test_invalid_text_prj_returns_none_not_an_error(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    data_path = _write_pair(tmp_path, "invalid_prj", "xyz", "this is not WKT at all")
    assert detector.detect(data_path) is None


def test_missing_main_file_raises_file_not_found(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    with pytest.raises(FileNotFoundError, match="not found"):
        detector.detect(tmp_path / "does_not_exist.xyz")


