def test_sidecar_naming_replaces_extension_not_appends(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    """survey.xyz -> survey.prj, never survey.xyz.prj -- matching the real Shapefile convention exactly."""
    wkt = pyproj.CRS.from_epsg(32618).to_wkt()
    data_path = tmp_path / "survey.xyz"
    data_path.write_text("fake data", encoding="utf-8")
    (tmp_path / "survey.prj").write_text(wkt, encoding="utf-8")
    (tmp_path / "survey.xyz.prj").write_text("this should never be read", encoding="utf-8")

    detected = detector.detect(data_path)
    assert detected is not None
    assert detected.epsg == 32618


def test_all_4_formats_sharing_one_base_name_use_the_same_sidecar(
    tmp_path: Path, detector: ExternalCRSDetector
) -> None:
    wkt = pyproj.CRS.from_epsg(32618).to_wkt()
    (tmp_path / "shared.prj").write_text(wkt, encoding="utf-8")

    for extension in ["xyz", "csv", "pts", "ply"]:
        data_path = tmp_path / f"shared.{extension}"
        data_path.write_text("fake data", encoding="utf-8")
        detected = detector.detect(data_path)
        assert detected is not None
        assert detected.epsg == 32618


def test_accepts_str_path_as_well_as_path_object(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    wkt = pyproj.CRS.from_epsg(32618).to_wkt()
    data_path = _write_pair(tmp_path, "str_path_test", "xyz", wkt)

    detected = detector.detect(str(data_path))
    assert detected is not None
    assert detected.epsg == 32618


