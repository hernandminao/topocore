def test_utf8_bom_is_stripped_correctly(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    """
    A real, confirmed bug found and fixed during this audit: a
    Windows/ESRI-style .prj with a UTF-8 byte-order-mark used to fail
    entirely (the decoded BOM character stayed at the start of the
    text, breaking CRS.from_wkt()). Fixed by reading with
    utf-8-sig instead of plain utf-8.
    """
    wkt = pyproj.CRS.from_epsg(32618).to_wkt()
    data_path = tmp_path / "with_bom.xyz"
    data_path.write_text("fake data", encoding="utf-8")
    (tmp_path / "with_bom.prj").write_bytes(b"\xef\xbb\xbf" + wkt.encode("utf-8"))

    detected = detector.detect(data_path)
    assert detected is not None
    assert detected.epsg == 32618


def test_compound_horizontal_and_vertical_crs_in_prj(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    compound = pyproj.CRS.from_epsg("32618+5773")
    data_path = _write_pair(tmp_path, "compound", "xyz", compound.to_wkt())

    detected = detector.detect(data_path)
    assert detected is not None
    assert detected.is_compound


def test_alternate_candidate_name_is_never_consulted(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    """
    Confirmed directly: only the exact `with_suffix('.prj')` path is
    ever checked. If `survey.prj` doesn't exist, `survey.xyz.prj`
    existing on its own is NOT treated as a fallback candidate --
    there is no "try alternate names" behavior at all.
    """
    data_path = tmp_path / "only_alternate.xyz"
    data_path.write_text("fake data", encoding="utf-8")
    wkt = pyproj.CRS.from_epsg(32618).to_wkt()
    (tmp_path / "only_alternate.xyz.prj").write_text(wkt, encoding="utf-8")  # NOT the canonical "only_alternate.prj"

    assert detector.detect(data_path) is None


def test_leading_comment_or_blank_lines_before_wkt_returns_none(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    """
    Confirmed directly: real .prj files are conventionally pure,
    single-line WKT with no comment syntax of their own. A file with
    leading blank lines or a comment-like line before the actual WKT
    is not parsed -- this is a deliberate conservative choice (never
    guess at an informal convention with no real precedent), not a
    best-effort extraction.
    """
    wkt = pyproj.CRS.from_epsg(32618).to_wkt()
    data_path = tmp_path / "with_comment.xyz"
    data_path.write_text("fake data", encoding="utf-8")
    (tmp_path / "with_comment.prj").write_text(f"\n\n# Generated by Some Software v1.0\n\n{wkt}\n", encoding="utf-8")

    assert detector.detect(data_path) is None


def test_permission_error_is_a_subclass_of_the_caught_oserror() -> None:
    """
    Confirmed structurally correct, even though this project's own
    development environment runs as root (bypassing Unix file
    permission checks entirely, so the actual OS-level denial itself
    cannot be forced and demonstrated directly here):
    PermissionError is a genuine subclass of the OSError this
    detector already catches, so a real permission-denied .prj would
    be treated the same as a missing one -- None, never an
    unhandled exception.
    """
    assert issubclass(PermissionError, OSError)


def test_non_epsg_crs_name_placeholder_documented_precisely(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    """
    Confirmed directly: a custom, unregistered CRS's own `.name` is
    the literal string "unknown" (pyproj's own generic placeholder).
    ExternalCRSDetector.detect() itself just returns the CRS object
    unchanged in this case -- the "unknown" string only appears later,
    at the point apply_external_crs() builds cloud.crs from it. This
    test locks in the CRS object's own state at the detector level.
    """
    custom_crs = pyproj.CRS.from_proj4(
        "+proj=lcc +lat_1=4 +lat_2=6 +lat_0=5 +lon_0=-74 +x_0=500000 "
        "+y_0=500000 +ellps=GRS80 +units=m +no_defs +type=crs"
    )
    data_path = _write_pair(tmp_path, "unnamed_crs", "xyz", custom_crs.to_wkt())

    detected = detector.detect(data_path)
    assert detected is not None
    assert detected.epsg is None
    assert detected.name == "unknown"
