"""
Tests for topocore.io.crs.external.ExternalCRSDetector.

The shared .prj sidecar strategy for formats with no CRS mechanism
of their own (XYZ, CSV, PTS, PLY -- confirmed during this
capability's own audit that none of these has any internal CRS
concept at all). Verified against both OGC-style and genuine
ESRI-style WKT1 (the conventional .prj dialect), across all 4
formats sharing a single .prj sidecar, and every failure mode from
the design's own explicit behavior table.
"""

from __future__ import annotations

from pathlib import Path

import pyproj
import pytest
from pyproj.enums import WktVersion
from topocore.geodesy import CRS
from topocore.io.crs.external import ExternalCRSDetector


@pytest.fixture
def detector() -> ExternalCRSDetector:
    return ExternalCRSDetector()


def _write_pair(tmp_path: Path, base_name: str, extension: str, prj_content: str | None) -> Path:
    data_path = tmp_path / f"{base_name}.{extension}"
    data_path.write_text("fake data content", encoding="utf-8")
    if prj_content is not None:
        (tmp_path / f"{base_name}.prj").write_text(prj_content, encoding="utf-8")
    return data_path


# ----------------------------------------------------------------------
# The explicit behavior table, verified exactly, across all 4 formats.
# ----------------------------------------------------------------------


@pytest.mark.parametrize("extension", ["xyz", "csv", "pts", "ply"])
def test_valid_ogc_wkt_prj_is_detected_for_every_supported_format(
    tmp_path: Path, detector: ExternalCRSDetector, extension: str
) -> None:
    wkt = pyproj.CRS.from_epsg(32618).to_wkt()
    data_path = _write_pair(tmp_path, "survey", extension, wkt)

    detected = detector.detect(data_path)
    assert detected is not None
    assert isinstance(detected, CRS)
    assert detected.epsg == 32618


def test_esri_style_wkt1_prj_is_detected(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    """
    Confirmed directly: .prj conventionally holds the older,
    ESRI-flavored WKT1 dialect -- verified here with a real one
    generated by pyproj itself, correctly resolved back to its own
    EPSG code with no special-casing needed.
    """
    esri_wkt = pyproj.CRS.from_epsg(26910).to_wkt(WktVersion.WKT1_ESRI)
    assert "D_North_American_1983" in esri_wkt  # confirm this really is the ESRI dialect
    data_path = _write_pair(tmp_path, "esri_survey", "xyz", esri_wkt)

    detected = detector.detect(data_path)
    assert detected is not None
    assert detected.epsg == 26910


def test_missing_prj_returns_none(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    data_path = _write_pair(tmp_path, "no_sidecar", "xyz", prj_content=None)
    assert detector.detect(data_path) is None


def test_empty_prj_returns_none(tmp_path: Path, detector: ExternalCRSDetector) -> None:
    data_path = _write_pair(tmp_path, "empty_prj", "xyz", "")
